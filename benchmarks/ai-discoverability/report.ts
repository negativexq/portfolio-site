import { writeFileSync } from "node:fs";
import { formatBytes, formatPercent } from "./metrics.ts";
import type { BenchmarkReport } from "./types.ts";

/** Pure: given a report, returns Markdown. No filesystem access, so this is
 * directly unit-testable with fixture data (see report.test.ts) -- the
 * file itself is not manually maintained, it's overwritten by
 * writeReportFile() on every `npm run benchmark:ai`. */
export function renderReportMarkdown(report: BenchmarkReport): string {
  const { discovery, tokenEfficiency, retrieval, accuracy, http } = report;

  const httpRows = http
    .map(
      (row) =>
        `| ${row.markdownPath} | ${formatBytes(row.htmlBytes)} | ${formatBytes(row.markdownBytes)} | ${formatPercent(row.sizeReductionPercent)} | ${row.htmlLatencyMs.toFixed(0)} ms | ${row.markdownLatencyMs.toFixed(0)} ms |`,
    )
    .join("\n");

  return `# AI Discoverability Benchmark Report

Generated: ${report.generatedAt}
Benchmark version: ${report.benchmarkVersion}
Target: ${report.baseUrl}
Questions evaluated: ${report.questionCount}

This report is generated by \`npm run benchmark:ai\` and overwritten on every
run -- it is not hand-edited. See \`README.md\` in this directory for
methodology and limitations.

## 1. Discovery

| | Resources | Requests | Bytes | Latency | Required info found |
|---|---|---|---|---|---|
| ${discovery.html.label} | ${discovery.html.resources.join(", ")} | ${discovery.html.requestCount} | ${formatBytes(discovery.html.totalBytes)} | ${discovery.html.totalLatencyMs.toFixed(0)} ms | ${discovery.html.requiredInfoFound ? "yes" : "no"} |
| ${discovery.ai.label} | ${discovery.ai.resources.join(", ")} | ${discovery.ai.requestCount} | ${formatBytes(discovery.ai.totalBytes)} | ${discovery.ai.totalLatencyMs.toFixed(0)} ms | ${discovery.ai.requiredInfoFound ? "yes" : "no"} |

## 2. Token Efficiency

| | Characters | Estimated tokens |
|---|---|---|
| HTML (\`/\`) | ${tokenEfficiency.htmlCharacters.toLocaleString()} | ${tokenEfficiency.htmlEstimatedTokens.toLocaleString()} |
| Markdown (\`/llms.txt\` + \`/resume.md\` + \`/projects.md\`) | ${tokenEfficiency.markdownCharacters.toLocaleString()} | ${tokenEfficiency.markdownEstimatedTokens.toLocaleString()} |

Reduction: **${formatPercent(tokenEfficiency.reductionPercent)}**. Token counts are a \`chars / 4\` estimate, not a real tokenizer -- see README.

## 3. Retrieval (lexical, not embedding-based -- see README)

| | Recall@1 | Recall@3 | Recall@5 |
|---|---|---|---|
| HTML corpus | ${retrieval.html.recallAt1.toFixed(2)} | ${retrieval.html.recallAt3.toFixed(2)} | ${retrieval.html.recallAt5.toFixed(2)} |
| Markdown corpus | ${retrieval.markdown.recallAt1.toFixed(2)} | ${retrieval.markdown.recallAt3.toFixed(2)} | ${retrieval.markdown.recallAt5.toFixed(2)} |

Evaluated against ${retrieval.html.questionsEvaluated} questions.

## 4. Answer Accuracy (deterministic fact-presence proxy, not an LLM judge)

| | Fact presence rate |
|---|---|
| HTML context | ${formatPercent(accuracy.htmlFactPresenceRate)} |
| Markdown context | ${formatPercent(accuracy.markdownFactPresenceRate)} |

Evaluated against ${accuracy.questionsEvaluated} questions. No LLM call was made -- see README for why, and for the optional extension point.

## 5. HTTP Comparison

| Markdown route | HTML size | Markdown size | Size reduction | HTML latency | Markdown latency |
|---|---|---|---|---|---|
${httpRows}

## Limitations

- Token counts are a character-based estimate, not a real BPE tokenizer.
- Retrieval uses lexical keyword overlap, not semantic embeddings -- it
  measures "does the Markdown/HTML surface the right document for an
  obvious keyword match", not full RAG retrieval quality.
- Accuracy is fact-presence in context, not a graded LLM answer -- it
  measures groundedness of the available context, not whether an agent
  would actually compose a correct answer from it.
- Latency figures are single-request wall-clock time against one local
  server process, not a statistically robust benchmark across network
  conditions or multiple runs.
- The HTML discovery/retrieval baseline has no \`/skills\` page at all (only
  \`/skills.md\` exists), so skills-sourced questions can score zero on the
  HTML side by construction -- that is a real finding about the site, not a
  benchmark defect.
- Retrieval recall does not clearly favor Markdown the way the other four
  metrics do, and that is a genuine result worth stating plainly rather than
  explaining away: this site's HTML is already server-rendered with real
  text (titles, summaries, technology tags), so a keyword-overlap retriever
  finds much of the same vocabulary in both representations. Markdown's
  advantage here shows up as conciseness and fact completeness (see Token
  Efficiency and Answer Accuracy above), not as a retrieval-surface
  difference a purely lexical retriever can detect.
`;
}

export function writeReportFile(report: BenchmarkReport, filePath: string): void {
  writeFileSync(filePath, renderReportMarkdown(report));
}
